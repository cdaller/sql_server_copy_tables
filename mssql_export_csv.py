#!/usr/bin/env -S uv run --script

import sys
import struct
import argparse
import csv
import json
import os
from time import perf_counter

from mssql_import_csv import create_connection, Progress
from mssql_reorder_columns import get_column_info, get_key_constraints, get_indexes, get_check_constraints, get_foreign_keys

# column keys in the order of the rows returned by mssql_reorder_columns.get_column_info
COLUMN_KEYS = ['name', 'type_name', 'max_length', 'precision', 'scale', 'is_nullable', 'column_id',
               'default_definition', 'is_identity', 'identity_seed', 'identity_incr']

# rowversion/timestamp values are generated by the server and cannot be inserted
NOT_EXPORTED_TYPES = {'timestamp'}

SQL_SS_TIMESTAMPOFFSET = -155


def parse_args():
    parser = argparse.ArgumentParser(description='Export a SQL Server table into a CSV file and its table definition (columns, keys, constraints, indexes) into a JSON file.')
    parser.add_argument('--driver', dest='driver', default='{ODBC Driver 18 for SQL Server}', help='ODBC driver (default: %(default)s)')
    parser.add_argument('--server', dest='server', required=True, help='database server name')
    parser.add_argument('--db', dest='db', required=True, help='database name')
    parser.add_argument('--authentication', dest='authentication', default='UsernamePassword', help='authentication method (default: %(default)s)')
    parser.add_argument('--user', dest='user', help='username (for UsernamePassword auth)')
    parser.add_argument('--password', dest='password', help='password (for UsernamePassword auth)')
    parser.add_argument('--table', dest='table', required=True, help='table name, optionally schema-qualified (e.g. dbo.MyTable)')
    parser.add_argument('--file', dest='file', required=True, help='CSV file to write')
    parser.add_argument('--json-file', dest='json_file', help='JSON file to write the table definition to (default: CSV file name with extension .json)')
    parser.add_argument('--where', dest='where', help='where clause to limit the exported rows (e.g. "year = 2026")')
    parser.add_argument('--delimiter', dest='delimiter', default=',', help='CSV field delimiter (default: %(default)s)')
    parser.add_argument('--encoding', dest='encoding', default='utf-8', help='CSV file encoding (default: %(default)s)')
    parser.add_argument('--page-size', dest='page_size', type=int, default=50000, help='number of rows fetched per page (default: %(default)s)')
    return parser


def convert_datetimeoffset(value):
    # pyodbc does not support datetimeoffset natively (see https://github.com/mkleehammer/pyodbc/wiki/Using-an-Output-Converter-function)
    year, month, day, hour, minute, second, nanoseconds, offset_hours, offset_minutes = struct.unpack('<6hI2h', value)
    sign = '-' if offset_hours < 0 or offset_minutes < 0 else '+'
    return (f'{year:04d}-{month:02d}-{day:02d} {hour:02d}:{minute:02d}:{second:02d}.{nanoseconds // 100:07d} '
            f'{sign}{abs(offset_hours):02d}:{abs(offset_minutes):02d}')


def get_table_definition(connection, schema, table):
    columns = []
    for row in get_column_info(connection, schema, table):
        column = dict(zip(COLUMN_KEYS, row))
        column['is_nullable'] = bool(column['is_nullable'])
        column['is_identity'] = bool(column['is_identity'])
        # IDENT_SEED/IDENT_INCR return decimals, which are not JSON serializable
        for key in ('identity_seed', 'identity_incr'):
            if column[key] is not None:
                column[key] = int(column[key])
        columns.append(column)

    return {
        'schema': schema,
        'table': table,
        'columns': columns,
        'key_constraints': get_key_constraints(connection, schema, table),
        'indexes': get_indexes(connection, schema, table),
        'check_constraints': get_check_constraints(connection, schema, table),
        'foreign_keys': get_foreign_keys(connection, schema, table),
    }


def format_value(value):
    if isinstance(value, (bytes, bytearray)):
        return '0x' + value.hex()
    return value


def export_csv(connection, schema, table, column_names, where_clause, file, delimiter, encoding, page_size):
    column_list = ', '.join(f'[{c}]' for c in column_names)
    where_sql = f" WHERE {where_clause}" if where_clause else ''

    with connection.cursor() as cursor:
        cursor.execute(f"SELECT COUNT_BIG(*) FROM [{schema}].[{table}]{where_sql}")
        total_rows = cursor.fetchone()[0]
    print(f" {total_rows:_} rows ...", end="", flush=True)

    progress = Progress(total_rows)
    page_count = 0

    with connection.cursor() as cursor, open(file, 'w', newline='', encoding=encoding) as f:
        # QUOTE_NOTNULL writes NULL as an unquoted empty field and all other values quoted,
        # so NULL and empty strings can be distinguished on import
        writer = csv.writer(f, delimiter=delimiter, quoting=csv.QUOTE_NOTNULL)
        writer.writerow(column_names)

        cursor.execute(f"SELECT {column_list} FROM [{schema}].[{table}]{where_sql}")
        while True:
            start_time_page = perf_counter()
            rows = cursor.fetchmany(page_size)
            if not rows:
                break
            writer.writerows([format_value(v) for v in row] for row in rows)
            page_count += 1
            progress.page_done(len(rows), f" {page_count}r({perf_counter() - start_time_page:.1f}s)")

    progress.done()


def main():
    parser = parse_args()
    ARGS = parser.parse_args()

    if '.' in ARGS.table:
        schema, table = ARGS.table.split('.', 1)
    else:
        schema = 'dbo'
        table = ARGS.table

    json_file = ARGS.json_file or os.path.splitext(ARGS.file)[0] + '.json'

    config = {
        'driver': ARGS.driver,
        'server': ARGS.server,
        'database': ARGS.db,
        'authentication': ARGS.authentication,
        'user': ARGS.user,
        'password': ARGS.password,
    }

    connection = None
    try:
        print(f'connecting to server {config["server"]} db {config["database"]}... ', end='', flush=True)
        connection = create_connection(config)
        connection.add_output_converter(SQL_SS_TIMESTAMPOFFSET, convert_datetimeoffset)
        print(' - DONE', flush=True)

        definition = get_table_definition(connection, schema, table)
        if not definition['columns']:
            print(f"ERROR: Table '{schema}.{table}' not found or has no columns.", file=sys.stderr)
            sys.exit(1)

        print(f"Writing table definition to {json_file}...", end="", flush=True)
        with open(json_file, 'w', encoding='utf-8') as f:
            json.dump(definition, f, indent=2)
        print(" - done")

        column_names = [c['name'] for c in definition['columns'] if c['type_name'] not in NOT_EXPORTED_TYPES]
        print(f"Exporting {schema}.{table}{' using where clause [' + ARGS.where + ']' if ARGS.where else ''} into {ARGS.file}...", end="", flush=True)
        export_csv(connection, schema, table, column_names, ARGS.where, ARGS.file, ARGS.delimiter, ARGS.encoding, ARGS.page_size)

    except Exception as e:
        print(f"\nAn error occurred: {e}", file=sys.stderr)
        import traceback
        traceback.print_exc(file=sys.stderr)
        sys.exit(1)
    finally:
        if connection:
            connection.close()


if __name__ == '__main__':
    main()
